#!/usr/bin/env node
/**
 * Generates the one-shot SQL that brings Supabase in line with the repo:
 *
 *   1. inserts quizzes that exist only in quizzes/*.json (idempotent by id)
 *   2. drops the duplicate "Examen de Semiologia 2024" row, only if unused
 *   3. repairs the mangled "Neurocognitivo y Psiquiatr?a" title
 *   4. adds stable option ids to academy_quiz_questions and backfills them
 *
 * Option ids are computed here with src/lib/optionIds.js, the very module the
 * client uses, so the stored values cannot drift from what the app derives.
 *
 * Usage: node scripts/generate-sync-sql.mjs
 */
import { readFileSync, writeFileSync, readdirSync } from 'fs'
import { fileURLToPath } from 'url'
import { dirname, resolve } from 'path'
import { buildOptionIds } from '../src/lib/optionIds.js'

/**
 * Rows already in Supabase only need their new ids set, not a full re-insert,
 * which keeps the file small enough to paste into the SQL Editor.
 */
async function fetchExistingIds() {
  const env = {}
  try {
    for (const line of readFileSync(resolve(root, '.env.local'), 'utf-8').split('\n')) {
      const m = line.match(/^([A-Z0-9_]+)=(.*)$/)
      if (m) env[m[1]] = m[2].replace(/^"|"$/g, '').replace(/\\r\\n$/, '')
    }
  } catch {
    // no .env.local: treat everything as missing
  }
  const url = process.env.VITE_SUPABASE_URL || env.VITE_SUPABASE_URL
  const key = process.env.VITE_SUPABASE_ANON_KEY || env.VITE_SUPABASE_ANON_KEY
  if (!url || !key) {
    console.warn('Sin credenciales: genero INSERTs para todo (idempotentes igual).')
    return { quizzes: new Set(), questions: new Set() }
  }

  const get = async path => {
    const res = await fetch(`${url}/rest/v1/${path}`, {
      headers: { apikey: key, Authorization: `Bearer ${key}` }
    })
    if (!res.ok) throw new Error(`${path} -> ${res.status}`)
    return res.json()
  }

  const [quizRows, questionRows] = await Promise.all([
    get('academy_quizzes?select=id'),
    get('academy_quiz_questions?select=id&limit=5000')
  ])
  return {
    quizzes: new Set(quizRows.map(r => r.id)),
    questions: new Set(questionRows.map(r => r.id))
  }
}

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')

const DUPLICATE_QUIZ_ID = 'de9aa85a-e3b2-4058-9ff1-aa16916835aa' // Semiologia, created 5s after its twin
const MANGLED_TITLE_QUIZ_ID = '1eb7f501-e3c6-417d-9c38-b3dfa0c1698f'

const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i

/** Single-quoted SQL literal, or NULL. */
function lit(value) {
  if (value === null || value === undefined) return 'NULL'
  return `'${String(value).replace(/'/g, "''")}'`
}

/** Numeric SQL literal with a fallback, so a missing field never emits `undefined`. */
function num(value, fallback) {
  return typeof value === 'number' && Number.isFinite(value) ? String(value) : String(fallback)
}

function textArray(values) {
  if (!values.length) return "'{}'::text[]"
  return `ARRAY[${values.map(lit).join(', ')}]::text[]`
}

const files = readdirSync(resolve(root, 'quizzes')).filter(f => f.endsWith('.json'))
const quizzes = files.map(file => ({
  file,
  ...JSON.parse(readFileSync(resolve(root, 'quizzes', file), 'utf-8'))
}))

const out = []
out.push('-- Generated by scripts/generate-sync-sql.mjs — do not edit by hand.')
out.push('-- Run once in the Supabase SQL Editor. Safe to re-run: every statement is idempotent.')
out.push('')
out.push('begin;')
out.push('')

// ---- 1. schema ----------------------------------------------------------
out.push('-- 1. Stable option ids: the correct answer stops being an array position.')
out.push('alter table academy_quiz_questions')
out.push('  add column if not exists option_ids text[],')
out.push('  add column if not exists correct_option_id text;')
out.push('')
out.push("comment on column academy_quiz_questions.option_ids is 'Stable id per option, derived from its text (src/lib/optionIds.js). Reordering options no longer moves the correct answer.';")
out.push("comment on column academy_quiz_questions.correct_option_id is 'Value of option_ids that is correct. correct_option_index is kept for older clients.';")
out.push('')

// ---- 2. content only present in the repo --------------------------------
const repoOnly = quizzes.filter(q => !UUID_RE.test(q.quiz.id ?? ''))
if (repoOnly.length) {
  throw new Error(
    `Estos quizzes no tienen UUID todavía: ${repoOnly.map(q => q.file).join(', ')}\n` +
      'Asigná uno con scripts/assign-quiz-uuid.mjs antes de generar el SQL.'
  )
}

const existing = await fetchExistingIds()

// --- 2a. rows already in Supabase: just set the new ids ------------------
const updates = []
for (const { quiz, questions } of quizzes) {
  for (const q of questions) {
    if (!existing.questions.has(q.id)) continue
    const optionIds = buildOptionIds(q.options)
    const correctId = optionIds[q.correct_option_index] ?? optionIds[0]
    updates.push(`  (${lit(q.id)}::uuid, ${textArray(optionIds)}, ${lit(correctId)})`)
  }
  void quiz
}

if (updates.length) {
  out.push(`-- 2. Backfill stable ids on the ${updates.length} questions already stored.`)
  out.push('update academy_quiz_questions q')
  out.push('set option_ids = v.option_ids, correct_option_id = v.correct_option_id')
  out.push('from (values')
  out.push(updates.join(',\n'))
  out.push(') as v(id, option_ids, correct_option_id)')
  out.push('where q.id = v.id;')
  out.push('')
}

// --- 2b. content that exists only in the repo ----------------------------
const missing = quizzes.filter(({ quiz }) => !existing.quizzes.has(quiz.id))
for (const { quiz, questions } of missing) {
  out.push(`-- 3. "${quiz.title}" lives only in the repo; create it.`)
  out.push(`insert into academy_quizzes (id, title, description, time_limit_minutes, passing_score, shuffle_questions, show_correct_answers, status, created_by)`)
  out.push(
    `values (${lit(quiz.id)}, ${lit(quiz.title)}, ${lit(quiz.description)}, ` +
      `${quiz.time_limit_minutes == null ? 'NULL' : num(quiz.time_limit_minutes, 'NULL')}, ` +
      `${quiz.passing_score == null ? 'NULL' : num(quiz.passing_score, 'NULL')}, ` +
      `${quiz.shuffle_questions ? 'true' : 'false'}, ${quiz.show_correct_answers === false ? 'false' : 'true'}, ` +
      `'published', 'repo-sync')`
  )
  out.push('on conflict (id) do nothing;')
  out.push('')

  questions.forEach((q, index) => {
    const optionIds = buildOptionIds(q.options)
    const correctId = optionIds[q.correct_option_index] ?? optionIds[0]
    out.push(
      `insert into academy_quiz_questions (id, quiz_id, question_text, question_type, options, correct_option_index, option_ids, correct_option_id, explanation, points, display_order)`
    )
    out.push(
      `values (${lit(q.id)}, ${lit(quiz.id)}, ${lit(q.question_text)}, ${lit(q.question_type || 'multiple_choice')}, ` +
        `${textArray(q.options)}, ${num(q.correct_option_index, 0)}, ${textArray(optionIds)}, ${lit(correctId)}, ` +
        `${lit(q.explanation)}, ${num(q.points, 1)}, ${num(q.display_order, index)})`
    )
    out.push('on conflict (id) do update set')
    out.push('  option_ids = excluded.option_ids,')
    out.push('  correct_option_id = excluded.correct_option_id;')
    out.push('')
  })
}

// ---- 3. data repairs ----------------------------------------------------
out.push('-- 4. Repair the title mangled on import (shows up in the ranking view).')
out.push(
  `update academy_quizzes set title = ${lit('Neurocognitivo y Psiquiatría')} where id = ${lit(MANGLED_TITLE_QUIZ_ID)};`
)
out.push('')
out.push('-- 5. Retire the exact duplicate of "Examen de Semiologia 2024" (created 5s after its twin).')
out.push('--    Delete it when unused; if somebody already sat it, archive instead so their')
out.push('--    attempts survive. Either way it stops showing in the app.')
out.push('delete from academy_quiz_questions')
out.push(`where quiz_id = ${lit(DUPLICATE_QUIZ_ID)}`)
out.push(`  and not exists (select 1 from academy_quiz_attempts a where a.quiz_id = ${lit(DUPLICATE_QUIZ_ID)});`)
out.push('delete from academy_quizzes')
out.push(`where id = ${lit(DUPLICATE_QUIZ_ID)}`)
out.push(`  and not exists (select 1 from academy_quiz_attempts a where a.quiz_id = ${lit(DUPLICATE_QUIZ_ID)});`)
out.push('')
out.push('update academy_quizzes')
out.push("set status = 'archived'")
out.push(`where id = ${lit(DUPLICATE_QUIZ_ID)} and status <> 'archived';`)
out.push('')

// ---- 5. report ----------------------------------------------------------
out.push('-- 6. Report: what the database looks like afterwards.')
out.push('do $$')
out.push('declare')
out.push('  pending int;')
out.push('  dup int;')
out.push('begin')
out.push('  select count(*) into pending from academy_quiz_questions where correct_option_id is null;')
out.push(`  select count(*) into dup from academy_quizzes where id = ${lit(DUPLICATE_QUIZ_ID)} and status = 'published';`)
out.push("  raise notice 'preguntas sin id estable: %', pending;")
out.push("  raise notice 'duplicado de Semiologia visible en la app: %', dup;")
out.push('end $$;')
out.push('')
out.push('commit;')
out.push('')

const sql = out.join('\n')

// A bare `undefined`/`NaN` in generated SQL is read by Postgres as a column name;
// fail loudly here rather than shipping a file that dies mid-run.
const bad = sql.split('\n').filter(line => /(?<!')\b(undefined|NaN)\b(?!')/.test(line))
if (bad.length) {
  console.error(`Valores inválidos en ${bad.length} línea(s):`)
  bad.slice(0, 5).forEach(line => console.error('  ', line.slice(0, 120)))
  process.exit(1)
}

const target = resolve(root, 'supabase/migrations/20260807000000_sync_repo_and_stable_option_ids.sql')
writeFileSync(target, sql)

const totalQuestions = quizzes.reduce((n, q) => n + q.questions.length, 0)
console.log(`${quizzes.length} quizzes / ${totalQuestions} preguntas`)
console.log(`  ${updates.length} preguntas existentes -> backfill de ids`)
console.log(`  ${missing.length} quiz(zes) nuevos -> insert completo`)
console.log(`SQL: ${target}`)
